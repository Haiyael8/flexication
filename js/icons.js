export function icon(name) {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', '2');
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  svg.setAttribute('class', 'icon');
  svg.innerHTML = PATHS[name] || '';
  return svg;
}

export function applyIcons(root = document) {
  for (const node of root.querySelectorAll('[data-icon]')) {
    if (!node.querySelector(':scope > svg.icon')) node.prepend(icon(node.dataset.icon));
  }
  for (const node of root.querySelectorAll('[data-icon-after]')) {
    if (!node.querySelector(':scope > svg.icon')) node.append(icon(node.dataset.iconAfter));
  }
}
